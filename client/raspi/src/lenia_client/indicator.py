import time
import errno
import subprocess
from pathlib import Path


class HardwarePWM:
    # RP1 PWM0 channel 2 on GPIO18, using the Linux PWM interface.

    PERIOD_NS = 500_000  # 2 kHz, generated by the peripheral rather than Python.

    def __init__(self, root=Path('/sys/class/pwm'), configure_pin=None):
        chips = [p for p in root.glob('pwmchip*')
                 if p.resolve().parent.parent.name == '1f00098000.pwm']
        if len(chips) != 1:
            raise OSError('RP1 PWM0 controller unavailable; see wiki/wiring/indicator-led.md')
        chip = chips[0]
        self.channel = chip / 'pwm2'
        if not self.channel.exists():
            try:
                (chip / 'export').write_text('2')
            except OSError as error:
                if error.errno != errno.EBUSY:
                    raise
        # udev assigns the gpio group after export.
        for attempt in range(40):
            try:
                self._write('duty_cycle', 0)
                break
            except (FileNotFoundError, PermissionError):
                if attempt == 39:
                    raise
                time.sleep(.025)
        try:
            self._write('enable', 0)
            self._write('period', self.PERIOD_NS)
            self._write('polarity', 'normal')
            if configure_pin is None:
                subprocess.run(['/usr/bin/pinctrl', 'set', '18', 'a3'], check=True,
                               capture_output=True, text=True)
            else:
                configure_pin()
            self._write('enable', 1)
        except BaseException:
            self._write('duty_cycle', 0)
            raise
        self.duty = 0

    def _write(self, name, value):
        (self.channel / name).write_text(str(value))

    def set_brightness(self, value):
        duty = round(min(1.0, max(0.0, value)) * self.PERIOD_NS)
        if duty != self.duty:
            self._write('duty_cycle', duty)
            self.duty = duty

    def close(self):
        # Leave an enabled zero-duty signal: disabled PWM output is undefined.
        self._write('duty_cycle', 0)
        self.duty = 0


class IndicatorLight:
    MAX_BRIGHTNESS = .25

    def __init__(self, gpio=None):
        self.gpio = gpio if gpio is not None else HardwarePWM()
        self.brightness = self.MAX_BRIGHTNESS
        self.gpio.set_brightness(self.brightness)
        print('Indicator ready: GPIO18 / pin 12, 3.3 V hardware PWM at 2 kHz', flush=True)

    def update(self, population_fraction):
        self.brightness = self.MAX_BRIGHTNESS * min(1.0, max(0.0, population_fraction))
        self.gpio.set_brightness(self.brightness)

    def close(self):
        self.gpio.close()
